[DESCRIPTION]

- Actualiza cabecera en autorizadorsolicitud

*/


SELECT A.ID, A.solicitud_ID, C."ID" AS nueva_cabecera_ID
FROM BB83586B71A741C983DB97D08DF93F80.COM_CARREFOUR_JOURNAL_APROBADORSOLICITUD A
LEFT JOIN BB83586B71A741C983DB97D08DF93F80.COM_CARREFOUR_JOURNAL_CABECERAASIENTO C
  ON C.numeroSolicitud = A.solicitud_ID
WHERE C."ID" IS NOT NULL;

UPDATE BB83586B71A741C983DB97D08DF93F80.COM_CARREFOUR_JOURNAL_APROBADORSOLICITUD AS A
SET cabecera_ID = (
    SELECT C.ID
    FROM BB83586B71A741C983DB97D08DF93F80.COM_CARREFOUR_JOURNAL_CABECERAASIENTO AS C
    WHERE C.numeroSolicitud = A.solicitud_ID
)
WHERE EXISTS (
    SELECT 1
    FROM BB83586B71A741C983DB97D08DF93F80.COM_CARREFOUR_JOURNAL_CABECERAASIENTO AS C2
    WHERE C2.numeroSolicitud = A.solicitud_ID
);
