-- ============================================================
-- ABTP - Carrefour
-- ITSAP-1349 - Corrección de IDs de SubTipoAsiento 'J' y TipoCuenta 'PAC'
-- Si se dieron de alta con SYSUUID quedan sin guiones (ej. 6E3D5AD4E5A5D6021A0098FA9B49244A).
-- La app filtra por Edm.Guid y le agrega guiones al valor, por lo que no los encuentra
-- ("No existe configuración de adjuntos para el tipo y subtipo de asiento seleccionado.").
-- Se pasan a los IDs fijos de los CSV, actualizando primero las referencias.
-- Es idempotente: si los IDs ya son los correctos no modifica nada.
-- ============================================================

-- 1) Verificación previa
SELECT ID, CODIGO, NOMBRE FROM COM_CARREFOUR_JOURNAL_SUBTIPOASIENTO WHERE CODIGO = 'J';
SELECT ID, CODIGO, NOMBRE FROM COM_CARREFOUR_JOURNAL_TIPOCUENTA WHERE CODIGO = 'PAC';

-- 2) SubTipoAsiento 'J' -> 337eb64d-f4f5-40cc-8d13-8c7ac941483d
UPDATE COM_CARREFOUR_JOURNAL_CONFIGADJUNTOOBLIGATORIO
SET SUBTIPOASIENTO_ID = '337eb64d-f4f5-40cc-8d13-8c7ac941483d'
WHERE SUBTIPOASIENTO_ID IN (
    SELECT ID FROM COM_CARREFOUR_JOURNAL_SUBTIPOASIENTO
    WHERE CODIGO = 'J' AND ID <> '337eb64d-f4f5-40cc-8d13-8c7ac941483d'
);

UPDATE COM_CARREFOUR_JOURNAL_CABECERAASIENTO
SET SUBTIPOASIENTO_ID = '337eb64d-f4f5-40cc-8d13-8c7ac941483d'
WHERE SUBTIPOASIENTO_ID IN (
    SELECT ID FROM COM_CARREFOUR_JOURNAL_SUBTIPOASIENTO
    WHERE CODIGO = 'J' AND ID <> '337eb64d-f4f5-40cc-8d13-8c7ac941483d'
);

UPDATE COM_CARREFOUR_JOURNAL_SUBTIPOASIENTO
SET ID = '337eb64d-f4f5-40cc-8d13-8c7ac941483d'
WHERE CODIGO = 'J' AND ID <> '337eb64d-f4f5-40cc-8d13-8c7ac941483d';

-- 3) TipoCuenta 'PAC' -> 1da1a848-4ddd-4915-80b5-0f372cbe513f
UPDATE COM_CARREFOUR_JOURNAL_CUENTA
SET TIPO_ID = '1da1a848-4ddd-4915-80b5-0f372cbe513f'
WHERE TIPO_ID IN (
    SELECT ID FROM COM_CARREFOUR_JOURNAL_TIPOCUENTA
    WHERE CODIGO = 'PAC' AND ID <> '1da1a848-4ddd-4915-80b5-0f372cbe513f'
);

UPDATE COM_CARREFOUR_JOURNAL_TIPOCUENTA
SET ID = '1da1a848-4ddd-4915-80b5-0f372cbe513f'
WHERE CODIGO = 'PAC' AND ID <> '1da1a848-4ddd-4915-80b5-0f372cbe513f';

-- 4) Verificación posterior
SELECT ID, CODIGO, NOMBRE FROM COM_CARREFOUR_JOURNAL_SUBTIPOASIENTO WHERE CODIGO = 'J';
SELECT ID, CODIGO, NOMBRE FROM COM_CARREFOUR_JOURNAL_TIPOCUENTA WHERE CODIGO = 'PAC';

SELECT C.ID, T.CODIGO AS TIPO, S.CODIGO AS SUBTIPO, C.OBLIGATORIO
FROM COM_CARREFOUR_JOURNAL_CONFIGADJUNTOOBLIGATORIO C
JOIN COM_CARREFOUR_JOURNAL_TIPOASIENTO T ON C.TIPOASIENTO_ID = T.ID
JOIN COM_CARREFOUR_JOURNAL_SUBTIPOASIENTO S ON C.SUBTIPOASIENTO_ID = S.ID
WHERE S.CODIGO = 'J';

SELECT C.NUMERO, C.NOMBRE, T.CODIGO
FROM COM_CARREFOUR_JOURNAL_CUENTA C
JOIN COM_CARREFOUR_JOURNAL_TIPOCUENTA T ON C.TIPO_ID = T.ID
WHERE T.CODIGO = 'PAC';
